function f160(j, x, y, z) {
  if (j < 16) return x ^ y ^ z;
  if (j < 32) return (x & y) | (~x & z);
  if (j < 48) return (x | ~y) ^ z;
  if (j < 64) return (x & z) | (y & ~z);
  return x ^ (y | ~z);
}

const rotl = (x, n) => (x << n) | (x >>> (32 - n));

export function ripemd160(data) {
  const h = [0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476, 0xc3d2e1f0];
  const n = data.length;
  const total = ((n + 9 + 63) >> 6) << 6;
  const m = new Uint8Array(total);
  m.set(data);
  m[n] = 0x80;
  const bits = n * 8;
  const hi = Math.floor(bits / 0x100000000);
  m[total - 8] = bits; m[total - 7] = bits >>> 8; m[total - 6] = bits >>> 16; m[total - 5] = bits >>> 24;
  m[total - 4] = hi; m[total - 3] = hi >>> 8; m[total - 2] = hi >>> 16; m[total - 1] = hi >>> 24;
  const x = new Int32Array(16);
  for (let off = 0; off < total; off += 64) {
    for (let i = 0; i < 16; i++) x[i] = m[off + i * 4] | (m[off + i * 4 + 1] << 8) | (m[off + i * 4 + 2] << 16) | (m[off + i * 4 + 3] << 24);
    let al = h[0], bl = h[1], cl = h[2], dl = h[3], el = h[4];
    let ar = h[0], br = h[1], cr = h[2], dr = h[3], er = h[4];
    for (let j = 0; j < 80; j++) {
      const r = j >> 4;
      let t = (rotl((al + f160(j, bl, cl, dl) + x[RL[j]] + KL[r]) | 0, SL[j]) + el) | 0;
      al = el; el = dl; dl = rotl(cl, 10); cl = bl; bl = t;
      t = (rotl((ar + f160(79 - j, br, cr, dr) + x[RR[j]] + KR[r]) | 0, SR[j]) + er) | 0;
      ar = er; er = dr; dr = rotl(cr, 10); cr = br; br = t;
    }
    const t = (h[1] + cl + dr) | 0;
    h[1] = (h[2] + dl + er) | 0;
    h[2] = (h[3] + el + ar) | 0;
    h[3] = (h[4] + al + br) | 0;
    h[4] = (h[0] + bl + cr) | 0;
    h[0] = t;
  }
  const out = new Uint8Array(20);
  for (let i = 0; i < 5; i++) {
    out[i * 4] = h[i]; out[i * 4 + 1] = h[i] >>> 8; out[i * 4 + 2] = h[i] >>> 16; out[i * 4 + 3] = h[i] >>> 24;
  }
  return out;
}

export const toHex = (b) => Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");

export function fromHex(s) {
  if (typeof s !== "string" || s.length % 2 || /[^0-9a-f]/i.test(s)) throw new Error("not hex");
  const out = new Uint8Array(s.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(s.slice(i * 2, i * 2 + 2), 16);
  return out;
}
